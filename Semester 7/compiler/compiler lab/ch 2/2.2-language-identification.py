"""
Section 2.2 - Syntax Definition: Language Identification
Identify the language generated by several CFGs and test a string for membership.

  1. Balanced brackets     S -> ( S ) S | epsilon
  2. Equal a's and b's     S -> a S b S | b S a S | epsilon
  3. Prefix expressions    E -> op E E | id
  4. Postfix expressions   E -> E E op | id
"""
OPS = set("+-*/")


def balanced(s):
    depth = 0
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth < 0:
                return False, "a ')' appears before its '('"
        else:
            return False, f"'{ch}' is not a bracket"
    return depth == 0, ("brackets match" if depth == 0 else "unclosed '(' left")


def equal_ab(s):
    if any(ch not in "ab" for ch in s):
        return False, "only 'a' and 'b' are allowed"
    if s.count("a") == s.count("b"):
        return True, "number of a's equals number of b's"
    return False, f"{s.count('a')} a's but {s.count('b')} b's"


def expression(s, prefix):
    """Stack check: process right-to-left for prefix, left-to-right for postfix."""
    tokens = s.split()
    if not tokens:
        return False, "empty expression"
    stack = 0
    for tok in (reversed(tokens) if prefix else tokens):
        if tok in OPS:
            if stack < 2:
                return False, "operator has too few operands"
            stack -= 1
        elif tok.isdigit() or tok.isalpha():
            stack += 1
        else:
            return False, f"unknown token '{tok}'"
    return (stack == 1, "one expression remains" if stack == 1 else f"{stack} values left on stack")


LANGUAGES = {
    "1": ("Balanced brackets", "S -> ( S ) S | epsilon", "matched / properly nested parentheses", balanced),
    "2": ("Equal a's and b's", "S -> a S b S | b S a S | epsilon", "all strings with the same number of a's and b's", equal_ab),
    "3": ("Prefix expressions", "E -> + E E | - E E | * E E | / E E | id", "operators before their operands", lambda s: expression(s, True)),
    "4": ("Postfix expressions", "E -> E E + | E E - | E E * | E E / | id", "operators after their operands", lambda s: expression(s, False)),
}

if __name__ == "__main__":
    print("Languages and their grammars:")
    for key, (name, grammar, desc, _) in LANGUAGES.items():
        print(f"  {key}. {name}")
        print(f"       {grammar}")
        print(f"       Language: {desc}")

    choice = input("\nChoose a language [1-4] (or Enter for 1): ").strip() or "1"
    if choice not in LANGUAGES:
        print("Invalid choice.")
    else:
        name, grammar, desc, check = LANGUAGES[choice]
        examples = {"1": "(()())", "2": "aabbab", "3": "+ * a b c", "4": "a b + c *"}
        s = input(f"Enter a string for '{name}' (or Enter for '{examples[choice]}'): ").strip() or examples[choice]
        ok, why = check(s)
        print(f"\nGrammar : {grammar}")
        print(f"String  : '{s}'")
        print(f"Result  : {'ACCEPTED' if ok else 'REJECTED'} - {why}")
