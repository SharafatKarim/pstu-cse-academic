#!/usr/bin/env bash
set -e

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$DIR/../.." && pwd)"
BIN_DIR="$PROJECT_ROOT/src/bin"

mkdir -p "$BIN_DIR"
MINIC="$BIN_DIR/minic"
MINIC_VM="$BIN_DIR/minic-vm"

TMP_MC="/tmp/cli_test.mc"
TMP_MBC="/tmp/cli_test.mbc"

cat << 'EOF' > "$TMP_MC"
int main() {
    int a = 15;
    float b = 2.0;
    float c = a * b;
    println(c);
    return 0;
}
EOF

echo "=== 1. Testing compilation to .mbc ==="
"$MINIC" compile "$TMP_MC" -o "$TMP_MBC"
test -f "$TMP_MBC"

echo "=== 2. Testing --dump-ast ==="
AST_OUT=$("$MINIC" --dump-ast "$TMP_MC")
echo "$AST_OUT" | grep -q "FuncDef main"
echo "$AST_OUT" | grep -q "Decl a : int"

echo "=== 3. Testing --dump-sym ==="
SYM_OUT=$("$MINIC" --dump-sym "$TMP_MC")
echo "$SYM_OUT" | grep -q "Symbol Table"
echo "$SYM_OUT" | grep -q "a : int"

echo "=== 4. Testing --dump-typed-ast ==="
TYPED_OUT=$("$MINIC" --dump-typed-ast "$TMP_MC")
echo "$TYPED_OUT" | grep -q "Cast I2F"

echo "=== 5. Testing --disasm ==="
DISASM_OUT=$("$MINIC" --disasm "$TMP_MBC")
echo "$DISASM_OUT" | grep -q "Bytecode Disassembly"
echo "$DISASM_OUT" | grep -q "MUL_F"

echo "=== 6. Testing minic run --verbose ==="
RUN_OUT=$("$MINIC" run --verbose "$TMP_MC")
echo "$RUN_OUT" | grep -q "Stage 1: AST"
echo "$RUN_OUT" | grep -q "Stage 2: Symbol Table & Typed AST"
echo "$RUN_OUT" | grep -q "Stage 3: Generated Bytecode Disassembly"
echo "$RUN_OUT" | grep -q "Stage 4: VM Execution Trace"
echo "$RUN_OUT" | grep -q "30.000000"

echo "=== CLI Driver Tests Passed Successfully! ==="
